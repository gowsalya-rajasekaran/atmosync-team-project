
WITH route_metrics AS (

    SELECT
        ROUTE_ID,
        CONTAINER_ID,

        COUNT(EVENT_ID) AS TOTAL_GPS_EVENTS,

        COUNT(DISTINCT LEG_ID) AS TOTAL_TRANSPORT_LEGS,

        COUNT_IF(TRANSPORT_MODE = 'SEA') AS SEA_EVENTS,

        COUNT_IF(TRANSPORT_MODE = 'ROAD') AS ROAD_EVENTS,

        MIN(LOCATION_TIMESTAMP) AS FIRST_RECORDED_TIMESTAMP,

        MAX(LOCATION_TIMESTAMP) AS LATEST_RECORDED_TIMESTAMP,

        ROUND(AVG(SPEED_KMH), 2) AS AVG_SPEED_KMH,

        MAX_BY(LATITUDE, LOCATION_TIMESTAMP) AS LATEST_LATITUDE,

        MAX_BY(LONGITUDE, LOCATION_TIMESTAMP) AS LATEST_LONGITUDE

    FROM {{ ref('stg_container_gps') }}

    GROUP BY
        ROUTE_ID,
        CONTAINER_ID

)

SELECT
    ROUTE_ID,
    CONTAINER_ID,
    TOTAL_GPS_EVENTS,
    TOTAL_TRANSPORT_LEGS,
    SEA_EVENTS,
    ROAD_EVENTS,
    FIRST_RECORDED_TIMESTAMP,
    LATEST_RECORDED_TIMESTAMP,
    AVG_SPEED_KMH,
    LATEST_LATITUDE,
    LATEST_LONGITUDE

FROM route_metrics
