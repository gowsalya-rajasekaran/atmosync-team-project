WITH container_metrics AS (
    SELECT
        CONTAINER_ID,
        COMMODITY,
        COUNT(EVENT_ID) AS TOTAL_SENSOR_EVENTS,
        MAX_BY(QUANTITY_KG, EVENT_TIMESTAMP) AS LATEST_REPORTED_QUANTITY_KG,
        ROUND(AVG(TEMPERATURE), 2) AS AVG_TEMPERATURE,
        ROUND(AVG(HUMIDITY), 2) AS AVG_HUMIDITY,
        ROUND(AVG(VIBRATION), 2) AS AVG_VIBRATION,
        MIN(EVENT_TIMESTAMP) AS FIRST_EVENT_TIMESTAMP,
        MAX(EVENT_TIMESTAMP) AS LATEST_EVENT_TIMESTAMP
    FROM {{ ref('stg_avocado_sensors') }}
    GROUP BY
        CONTAINER_ID,
        COMMODITY
),

commodity_pricing AS (
    SELECT
        COMMODITY,
        PRICE_PER_KG
    FROM {{ ref('commodity_prices') }}
)

SELECT
    cm.*,
    cp.PRICE_PER_KG,
    ROUND(
        cm.LATEST_REPORTED_QUANTITY_KG * cp.PRICE_PER_KG,
        2
    ) AS ESTIMATED_CARGO_VALUE_INR
FROM container_metrics cm
LEFT JOIN commodity_pricing cp
    ON LOWER(cm.COMMODITY) = LOWER(cp.COMMODITY)
