
WITH leg_metrics AS (

    SELECT
        ROUTE_ID,
        CONTAINER_ID,
        LEG_ID,
        TRANSPORT_MODE,

        COUNT(EVENT_ID) AS TOTAL_GPS_EVENTS,

        MIN(LOCATION_TIMESTAMP) AS LEG_START_TIMESTAMP,

        MAX(LOCATION_TIMESTAMP) AS LEG_END_TIMESTAMP,

        ROUND(AVG(SPEED_KMH), 2) AS AVG_SPEED_KMH,

        MAX_BY(LATITUDE, LOCATION_TIMESTAMP)
            AS END_LATITUDE,

        MAX_BY(LONGITUDE, LOCATION_TIMESTAMP)
            AS END_LONGITUDE,

        MIN_BY(LATITUDE, LOCATION_TIMESTAMP)
            AS START_LATITUDE,

        MIN_BY(LONGITUDE, LOCATION_TIMESTAMP)
            AS START_LONGITUDE

    FROM {{ ref('stg_container_gps') }}

    GROUP BY
        ROUTE_ID,
        CONTAINER_ID,
        LEG_ID,
        TRANSPORT_MODE

)

SELECT
    ROUTE_ID,
    CONTAINER_ID,
    LEG_ID,
    TRANSPORT_MODE,
    TOTAL_GPS_EVENTS,
    LEG_START_TIMESTAMP,
    LEG_END_TIMESTAMP,
    AVG_SPEED_KMH,
    START_LATITUDE,
    START_LONGITUDE,
    END_LATITUDE,
    END_LONGITUDE

FROM leg_metrics
