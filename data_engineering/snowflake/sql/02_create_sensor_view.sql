USE DATABASE ATMOSYNC_DB;
USE SCHEMA RAW_DATA;

CREATE OR REPLACE VIEW CONTAINER_SENSOR_VIEW AS
SELECT
    EVENT_ID,
    RAW_PAYLOAD:timestamp::TIMESTAMP_NTZ AS EVENT_TIMESTAMP,
    RAW_PAYLOAD:container_id::VARCHAR AS CONTAINER_ID,
    RAW_PAYLOAD:temperature::FLOAT AS TEMPERATURE,
    RAW_PAYLOAD:humidity::FLOAT AS HUMIDITY,
    RAW_PAYLOAD:vibration::FLOAT AS VIBRATION,
    RAW_PAYLOAD:commodity::VARCHAR AS COMMODITY,
    RAW_PAYLOAD:quantity_kg::NUMBER(10,2) AS QUANTITY_KG,
    INGESTED_AT
FROM CONTAINER_EVENTS_RAW;

